//! Offline benchmark using only deterministic synthetic records and public APIs.
use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;
use std::sync::atomic::AtomicBool;
use std::time::Instant;

use archive_domain::{
    ArchiveBatchV1, BATCH_SCHEMA_VERSION, CollectionScope, EmployeeNoticeEvidence,
    ExternalContactConsent, LifecycleState, MESSAGE_SCHEMA_VERSION, MediaIntegrity, MediaRefV1,
    MessageDirection, MessageType, MessageV1, RetentionDirective,
};
use archive_export::export_streamed;
use archive_export::{ExportFormat, ExportPackage, ExportScope, export_package};
use archive_store::{ArchiveStore, MessageQuery};
use chrono::{DateTime, TimeDelta, Utc};
use serde_json::{Value, json};
use sha2::{Digest, Sha256};
use uuid::Uuid;
use wecom_archive_server::{ArchiveExportOptions, ArchiveExportSource};

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;
const BATCH_SIZE: usize = 2_000;

struct WorkDirectory(PathBuf);

impl Drop for WorkDirectory {
    fn drop(&mut self) {
        // This path is generated by this process, never accepted from user input.
        // Resolve it again before recursive cleanup; skip a replaced junction.
        let expected_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../target/benchmarks")
            .canonicalize();
        if let (Ok(root), Ok(work)) = (expected_root, self.0.canonicalize())
            && work.parent() == Some(root.as_path())
        {
            let _ = fs::remove_dir_all(&work);
        }
    }
}

fn timestamp(index: usize) -> chrono::DateTime<Utc> {
    DateTime::<Utc>::from_timestamp(1_735_689_600 + (index / 3) as i64, 0).unwrap()
}

fn batch(start: usize, count: usize, body_bytes: usize, generation: u128) -> ArchiveBatchV1 {
    let batch_id = Uuid::from_u128((generation << 64) | (start as u128 + 1));
    let messages: Vec<_> = (start..start + count)
        .map(|index| {
            let mut body = format!("synthetic archive message {index} 测试消息 ");
            if index % 10_000 == 0 {
                body.push_str("benchmarkneedle ");
            }
            body.extend(std::iter::repeat_n(
                'x',
                body_bytes.saturating_sub(body.len()),
            ));
            let media = if index % 20 == 0 {
                vec![MediaRefV1 {
                    content_hash: None,
                    original_name: Some("synthetic-file.txt".into()),
                    mime_type: Some("text/plain".into()),
                    size_bytes: None,
                    source_locator: "synthetic".into(),
                    integrity: MediaIntegrity::Missing,
                    missing_reason: Some("synthetic fixture has no media bytes".into()),
                }]
            } else {
                Vec::new()
            };
            MessageV1 {
                schema_version: MESSAGE_SCHEMA_VERSION.into(),
                source_kind: "synthetic".into(),
                source_instance_id: "synthetic-source".into(),
                source_message_id: format!("source-{index:09}"),
                stable_message_id: format!("stable-{index:09}"),
                // One large conversation and a long tail exercise both pagination patterns.
                conversation_id: if index % 2 == 0 {
                    "R:synthetic-hot".into()
                } else {
                    format!("R:synthetic-{:04}", (index / 2) % 1_000)
                },
                sender_id: Some(format!("synthetic-person-{:03}", index % 100)),
                sent_at: timestamp(index),
                direction: MessageDirection::Incoming,
                message_type: if media.is_empty() {
                    MessageType::Text
                } else {
                    MessageType::File
                },
                body_text: Some(body),
                quoted_message_id: None,
                lifecycle: LifecycleState::Active,
                media,
                raw_type: "synthetic".into(),
                raw_payload: json!({"synthetic": true}),
                parser_version: "benchmark.v1".into(),
                collection_batch_id: batch_id,
            }
        })
        .collect();
    let hash = Sha256::digest(serde_json::to_vec(&messages).unwrap());
    ArchiveBatchV1 {
        schema_version: BATCH_SCHEMA_VERSION.into(),
        batch_id,
        source_adapter: "synthetic".into(),
        source_instance_id: "synthetic-source".into(),
        collected_at: timestamp(start),
        employee_notice: EmployeeNoticeEvidence {
            notice_version: "synthetic.v1".into(),
            displayed_at: timestamp(0),
            acknowledged_at: Some(timestamp(0)),
            evidence_hash: "synthetic".into(),
        },
        external_contact_consent: ExternalContactConsent::NotApplicable,
        collection_scope: CollectionScope {
            source_ids: vec!["synthetic-source".into()],
            conversation_ids: Vec::new(),
            starts_at: None,
            ends_at: None,
            message_types: Vec::new(),
        },
        cursor_before: None,
        cursor_after: None,
        messages,
        content_sha256: hash.iter().map(|byte| format!("{byte:02x}")).collect(),
        retention: RetentionDirective {
            policy_id: None,
            expires_at: None,
            legal_hold: false,
        },
    }
}

fn measured<T>(
    metrics: &mut BTreeMap<String, Value>,
    name: &str,
    action: impl FnOnce() -> Result<T>,
) -> Result<T> {
    eprintln!("benchmark_phase={name}");
    let started = Instant::now();
    let result = action()?;
    metrics.insert(
        name.into(),
        json!({"elapsed_ms": started.elapsed().as_secs_f64() * 1000.0}),
    );
    Ok(result)
}

fn sampled(
    metrics: &mut BTreeMap<String, Value>,
    name: &str,
    samples: usize,
    mut action: impl FnMut() -> Result<()>,
) -> Result<()> {
    eprintln!("benchmark_phase={name}");
    let started = Instant::now();
    action()?;
    let first_ms = started.elapsed().as_secs_f64() * 1000.0;
    let mut times = Vec::new();
    for _ in 0..samples {
        let started = Instant::now();
        action()?;
        times.push(started.elapsed().as_secs_f64() * 1000.0);
    }
    times.sort_by(f64::total_cmp);
    metrics.insert(
        name.into(),
        json!({
            "first_ms": first_ms, "warm_samples": samples,
            "warm_p50_ms": times[(samples - 1) / 2],
            "warm_p95_ms": times[(samples * 95).div_ceil(100) - 1],
        }),
    );
    Ok(())
}

fn run() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    let count: usize = args.first().ok_or("missing count")?.parse()?;
    let body_bytes: usize = args.get(1).map(String::as_str).unwrap_or("256").parse()?;
    let samples: usize = args.get(2).map(String::as_str).unwrap_or("5").parse()?;
    let mode = args.get(3).map(String::as_str).unwrap_or("stream");
    if !matches!(mode, "stream" | "legacy") {
        return Err("invalid export mode".into());
    }
    if !(1_000..=1_000_000).contains(&count)
        || !(64..=4096).contains(&body_bytes)
        || !(1..=30).contains(&samples)
    {
        return Err("invalid benchmark parameters".into());
    }
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../target/benchmarks");
    fs::create_dir_all(&root)?;
    let work = WorkDirectory(root.join(format!("work-{}", Uuid::new_v4())));
    fs::create_dir(&work.0)?;
    let database = work.0.join("synthetic.db");
    let mut store = ArchiveStore::open(&database)?;
    let mut metrics = BTreeMap::new();
    let mut ingest_ms = 0.0;
    let started = Instant::now();
    eprintln!("benchmark_phase=initial_ingest");
    for start in (0..count).step_by(BATCH_SIZE) {
        let input = batch(start, BATCH_SIZE.min(count - start), body_bytes, 1);
        let timed = Instant::now();
        let summary = store.ingest_batch(&input)?;
        ingest_ms += timed.elapsed().as_secs_f64() * 1000.0;
        assert_eq!(summary.inserted, input.messages.len() as u64);
        assert_eq!(summary.revised + summary.unchanged, 0);
        let completed = start + input.messages.len();
        if completed.is_multiple_of(100_000) || completed == count {
            eprintln!("benchmark_ingested={completed}");
        }
    }
    assert_eq!(store.message_count()?, count as u64);
    metrics.insert("initial_ingest".into(), json!({
        "elapsed_ms": ingest_ms, "including_fixture_ms": started.elapsed().as_secs_f64() * 1000.0,
        "messages_per_second": count as f64 * 1000.0 / ingest_ms,
    }));
    let replay = batch(0, BATCH_SIZE.min(count), body_bytes, 1);
    measured(&mut metrics, "replay_batch", || {
        let summary = store.ingest_batch(&replay)?;
        assert_eq!(summary.unchanged, replay.messages.len() as u64);
        assert_eq!(summary.inserted + summary.revised, 0);
        Ok(())
    })?;
    let mut overlap = batch(0, BATCH_SIZE.min(count), body_bytes, 2);
    for message in &mut overlap.messages[..100] {
        message.body_text.as_mut().unwrap().push_str(" revised");
    }
    overlap.content_sha256 = Sha256::digest(serde_json::to_vec(&overlap.messages)?)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    measured(&mut metrics, "incremental_overlap_and_revisions", || {
        let summary = store.ingest_batch(&overlap)?;
        assert_eq!(summary.revised, 100);
        assert_eq!(summary.unchanged, overlap.messages.len() as u64 - 100);
        assert_eq!(summary.inserted, 0);
        Ok(())
    })?;
    let added = batch(count, 1_000, body_bytes, 3);
    measured(&mut metrics, "incremental_new_messages", || {
        assert_eq!(store.ingest_batch(&added)?.inserted, 1_000);
        Ok(())
    })?;
    let total = count + 1_000;
    assert_eq!(store.message_count()?, total as u64);
    drop((replay, overlap, added));
    // Verify cached counts against the generated dataset, outside query timing.
    let mut expected_statistics = BTreeMap::<String, (u64, u64)>::new();
    for index in 0..total {
        let conversation = if index % 2 == 0 {
            "R:synthetic-hot".into()
        } else {
            format!("R:synthetic-{:04}", (index / 2) % 1_000)
        };
        let counts = expected_statistics.entry(conversation).or_default();
        counts.0 += 1;
        counts.1 += u64::from(index % 20 == 0);
    }
    assert_eq!(
        store.count_messages(&MessageQuery {
            text: Some("revised".into()),
            ..Default::default()
        })?,
        100
    );
    sampled(&mut metrics, "conversation_list", samples, || {
        let conversations = store.list_conversations(100, 0)?;
        assert_eq!(conversations.len(), 100);
        assert!(
            conversations
                .windows(2)
                .all(|pair| pair[0].last_message_at >= pair[1].last_message_at)
        );
        for conversation in &conversations {
            assert_eq!(
                (conversation.message_count, conversation.media_count),
                expected_statistics[&conversation.conversation_id],
            );
        }
        Ok(())
    })?;
    for (name, conversation, offset) in [
        ("messages_global_first", None, 0),
        ("messages_global_deep", None, total as u64 * 4 / 5),
        ("messages_conversation_first", Some("R:synthetic-hot"), 0),
        (
            "messages_conversation_deep",
            Some("R:synthetic-hot"),
            total as u64 * 2 / 5,
        ),
    ] {
        sampled(&mut metrics, name, samples, || {
            let page = store.query_messages(&MessageQuery {
                conversation_id: conversation.map(str::to_owned),
                limit: 100,
                offset,
                ..Default::default()
            })?;
            assert_eq!(page.len(), 100);
            assert!(
                page.windows(2)
                    .all(|pair| (pair[0].sent_at, &pair[0].stable_message_id)
                        >= (pair[1].sent_at, &pair[1].stable_message_id))
            );
            Ok(())
        })?;
    }
    let fts = MessageQuery {
        text: Some("benchmarkneedle".into()),
        limit: 100,
        ..Default::default()
    };
    sampled(&mut metrics, "fts_search", samples, || {
        let page = store.query_messages(&fts)?;
        assert_eq!(page.len(), total.div_ceil(10_000).min(100));
        Ok(())
    })?;
    sampled(&mut metrics, "fts_count", samples, || {
        assert_eq!(store.count_messages(&fts)?, total.div_ceil(10_000) as u64);
        Ok(())
    })?;
    sampled(&mut metrics, "time_range", samples, || {
        let starts_at = timestamp(total / 2);
        let page = store.query_messages(&MessageQuery {
            starts_at: Some(starts_at),
            ends_at: Some(starts_at + TimeDelta::seconds(100)),
            limit: 100,
            ..Default::default()
        })?;
        assert_eq!(page.len(), 100);
        assert!(page.iter().all(|message| message.sent_at >= starts_at
            && message.sent_at <= starts_at + TimeDelta::seconds(100)));
        Ok(())
    })?;
    if mode == "stream" {
        let source = measured(&mut metrics, "export_prepare_stream", || {
            Ok(ArchiveExportSource::new(
                &store,
                ArchiveExportOptions {
                    query: MessageQuery {
                        sort_ascending: true,
                        ..Default::default()
                    },
                    conversation_order_ascending: true,
                    ..Default::default()
                },
            )?)
        })?;
        let mut package = ExportPackage {
            archive_id: "synthetic-benchmark".into(),
            scope: ExportScope::EntireArchive,
            format: ExportFormat::Json,
            messages: Vec::new(),
            participants: source.participants().to_vec(),
            conversation_names: source.conversation_names().clone(),
            simplify: false,
            pretty: false,
            media: Vec::new(),
            generated_at: timestamp(0),
            conversation_order_ascending: true,
            message_order_ascending: true,
        };
        for (name, format, extension) in [
            ("export_json", ExportFormat::Json, "json"),
            ("export_markdown", ExportFormat::Md, "md"),
            ("export_csv", ExportFormat::Csv, "csv"),
        ] {
            package.format = format;
            let target = work.0.join(format!("synthetic.{extension}"));
            measured(&mut metrics, name, || {
                let result = export_streamed(&package, &source, &target, &AtomicBool::new(false))?;
                assert_eq!(result.message_count, total as u64);
                assert_eq!(result.missing_media_count, total.div_ceil(20) as u64);
                assert!(
                    !target
                        .with_file_name(format!("synthetic.{extension}.partial"))
                        .exists()
                );
                Ok(())
            })?;
            metrics.get_mut(name).unwrap()["file_bytes"] = json!(fs::metadata(&target)?.len());
            fs::remove_file(target)?;
        }
    } else {
        let messages = measured(&mut metrics, "export_load_all", || {
            let mut messages = Vec::new();
            loop {
                let page = store.query_messages(&MessageQuery {
                    limit: 50_000,
                    offset: messages.len() as u64,
                    ..Default::default()
                })?;
                let last = page.len() < 50_000;
                messages.extend(page);
                if last {
                    break;
                }
            }
            messages.sort_by(|left, right| {
                (left.sent_at, &left.stable_message_id)
                    .cmp(&(right.sent_at, &right.stable_message_id))
            });
            assert_eq!(messages.len(), total);
            Ok(messages)
        })?;
        let mut package = ExportPackage {
            archive_id: "synthetic-benchmark".into(),
            scope: ExportScope::EntireArchive,
            format: ExportFormat::Json,
            messages,
            participants: Vec::new(),
            conversation_names: BTreeMap::new(),
            simplify: false,
            pretty: false,
            media: Vec::new(),
            generated_at: timestamp(0),
            conversation_order_ascending: true,
            message_order_ascending: true,
        };
        for (name, format, extension) in [
            ("export_json", ExportFormat::Json, "json"),
            ("export_markdown", ExportFormat::Md, "md"),
            ("export_csv", ExportFormat::Csv, "csv"),
        ] {
            package.format = format;
            let target = work.0.join(format!("synthetic.{extension}"));
            measured(&mut metrics, name, || {
                let result = export_package(&package, &target, &AtomicBool::new(false))?;
                assert_eq!(result.message_count, total as u64);
                assert_eq!(result.missing_media_count, total.div_ceil(20) as u64);
                assert!(
                    !target
                        .with_file_name(format!("synthetic.{extension}.partial"))
                        .exists()
                );
                Ok(())
            })?;
            metrics.get_mut(name).unwrap()["file_bytes"] = json!(fs::metadata(&target)?.len());
            fs::remove_file(target)?;
        }
    }
    drop(store);
    let database_bytes = fs::metadata(&database)?.len();
    println!(
        "{}",
        json!({
            "schema_version": "archive-benchmark.v2", "export_mode": mode, "dataset": "synthetic.v1",
            "storage_accelerators": "statistics-and-fts-rowids.batched.v1",
            "initial_messages": count, "final_messages": total, "body_bytes": body_bytes,
            "batch_size": BATCH_SIZE, "profile": if cfg!(debug_assertions) { "debug" } else { "release" },
            "query_samples": samples, "database_bytes_after_close": database_bytes, "metrics": metrics,
        })
    );
    Ok(())
}

fn main() {
    // Never print database errors or user paths in benchmark output.
    if run().is_err() {
        eprintln!("benchmark_failed");
        std::process::exit(1);
    }
}
